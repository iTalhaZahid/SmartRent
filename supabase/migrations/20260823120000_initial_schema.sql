create function public.validate_availability_write() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  perform pg_advisory_xact_lock(hashtextextended(new.property_id::text, 0));
  if new.status = 'BLOCKED' and exists (
    select 1 from public.bookings b
    where b.property_id = new.property_id
      and b.status in ('PENDING', 'APPROVED', 'ACTIVE')
      and daterange(b.start_date, b.end_date, '[)') && daterange(new.start_date, new.end_date, '[)')
  ) then
    raise exception 'Cannot block dates reserved by a live booking';
  end if;
  return new;
end;
$$;
create trigger availability_validate_write before insert or update on public.availability
for each row execute function public.validate_availability_write();

