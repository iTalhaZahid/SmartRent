create function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  requested_role public.user_role;
begin
  requested_role := case
    when new.raw_user_meta_data ->> 'role' = 'OWNER' then 'OWNER'::public.user_role
    else 'RENTER'::public.user_role
  end;

  insert into public.profiles (id, full_name, role)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''), requested_role);
  return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users
for each row execute function public.handle_new_user();

create function public.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'ADMIN' and status = 'ACTIVE'
  );
$$;

create function public.protect_profile_privileges() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if (select auth.uid()) is not null and not public.is_admin() then
    new.role := old.role;
    new.status := old.status;
  end if;
  return new;
end;
$$;
create trigger profiles_protect_privileges before update on public.profiles
for each row execute function public.protect_profile_privileges();

create function public.validate_booking_write() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  selected_property public.properties%rowtype;
  actor uuid := (select auth.uid());
  actor_role public.user_role;
begin
  if tg_op = 'INSERT' then
    perform pg_advisory_xact_lock(hashtextextended(new.property_id::text, 0));
    select * into selected_property from public.properties where id = new.property_id;
    select role into actor_role from public.profiles where id = actor and status = 'ACTIVE';

    if actor is not null and (actor <> new.renter_id or actor_role <> 'RENTER') then
      raise exception 'Only an active renter can create their own booking';
    end if;
    if selected_property.id is null or selected_property.status <> 'ACTIVE' then
      raise exception 'Property is not available for booking';
    end if;
    if selected_property.owner_id <> new.owner_id or new.renter_id = new.owner_id then
      raise exception 'Booking participants do not match the property';
    end if;
    if new.occupants > selected_property.max_occupants then
      raise exception 'Occupant count exceeds the property limit';
    end if;
    if not (
      selected_property.rental_mode = 'BOTH' or selected_property.rental_mode = new.rental_mode
    ) then
      raise exception 'Selected rental mode is not supported';
    end if;
    if exists (
      select 1 from public.availability a
      where a.property_id = new.property_id and a.status = 'BLOCKED'
        and daterange(a.start_date, a.end_date, '[)') && daterange(new.start_date, new.end_date, '[)')
    ) then
      raise exception 'Selected dates are blocked';
    end if;
    new.status := 'PENDING';
    new.estimated_cost := case new.rental_mode
      when 'SHORT_TERM' then (new.end_date - new.start_date) * selected_property.short_term_price
      when 'LONG_TERM' then greatest(1, ceil((new.end_date - new.start_date) / 30.0)) * selected_property.monthly_price
      else 0
    end;
  elsif actor is not null and not public.is_admin() then
    if actor = old.owner_id then
      if old.status <> 'PENDING' or new.status not in ('APPROVED', 'REJECTED') then
        raise exception 'Owner can only approve or reject a pending booking';
      end if;
    elsif actor = old.renter_id then
      if old.status not in ('PENDING', 'APPROVED') or new.status <> 'CANCELLED' then
        raise exception 'Renter can only cancel an eligible booking';
      end if;
    else
      raise exception 'Not authorized to update this booking';
    end if;

    new.property_id := old.property_id;
    new.renter_id := old.renter_id;
    new.owner_id := old.owner_id;
    new.rental_mode := old.rental_mode;
    new.start_date := old.start_date;
    new.end_date := old.end_date;
    new.occupants := old.occupants;
    new.estimated_cost := old.estimated_cost;
  end if;
  return new;
end;
$$;
create trigger bookings_validate_write before insert or update on public.bookings
for each row execute function public.validate_booking_write();

create function public.sync_booking_side_effects() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    insert into public.availability
      (property_id, booking_id, start_date, end_date, status, created_by)
    values
      (new.property_id, new.id, new.start_date, new.end_date, 'RESERVED', new.renter_id);
    insert into public.notifications (user_id, type, title, message, metadata)
    values (new.owner_id, 'BOOKING_REQUEST', 'New booking request',
      'A renter submitted a booking request for your property.', jsonb_build_object('booking_id', new.id));
  elsif new.status is distinct from old.status then
    if new.status = 'APPROVED' then
      update public.availability set status = 'BOOKED' where booking_id = new.id;
    elsif new.status in ('REJECTED', 'CANCELLED') then
      delete from public.availability where booking_id = new.id;
    end if;

    if new.status in ('APPROVED', 'REJECTED', 'CANCELLED') then
      insert into public.notifications (user_id, type, title, message, metadata)
      values (
        case when new.status = 'CANCELLED' then new.owner_id else new.renter_id end,
        case new.status
          when 'APPROVED' then 'BOOKING_APPROVED'::public.notification_type
          when 'REJECTED' then 'BOOKING_REJECTED'::public.notification_type
          else 'BOOKING_CANCELLED'::public.notification_type
        end,
        initcap(lower(new.status::text)) || ' booking',
        'Booking status changed to ' || new.status::text || '.',
        jsonb_build_object('booking_id', new.id)
      );
    end if;
  end if;
  return new;
end;
$$;
create trigger bookings_sync_side_effects after insert or update on public.bookings
for each row execute function public.sync_booking_side_effects();

