create extension if not exists btree_gist with schema extensions;

create type public.user_role as enum ('RENTER', 'OWNER', 'ADMIN');
create type public.user_status as enum ('ACTIVE', 'SUSPENDED');
create type public.rental_mode as enum ('SHORT_TERM', 'LONG_TERM', 'BOTH');
create type public.property_status as enum ('PENDING', 'ACTIVE', 'REJECTED', 'INACTIVE');
create type public.availability_status as enum ('RESERVED', 'BOOKED', 'BLOCKED');
create type public.booking_status as enum ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED', 'ACTIVE', 'COMPLETED');
create type public.lease_status as enum ('ACTIVE', 'COMPLETED', 'EXPIRED', 'TERMINATED');
create type public.notification_type as enum (
  'BOOKING_REQUEST', 'BOOKING_APPROVED', 'BOOKING_REJECTED',
  'BOOKING_CANCELLED', 'NEW_MESSAGE', 'LEASE_EXPIRING', 'SYSTEM_ALERT'
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text,
  role public.user_role not null default 'RENTER',
  avatar_url text,
  status public.user_status not null default 'ACTIVE',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint full_name_length check (char_length(full_name) <= 120)
);

create table public.properties (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  description text not null,
  address text not null,
  city text not null,
  property_type text not null,
  bedrooms smallint not null default 0 check (bedrooms >= 0),
  bathrooms numeric(3,1) not null default 0 check (bathrooms >= 0),
  max_occupants smallint not null check (max_occupants > 0),
  short_term_price numeric(12,2) check (short_term_price > 0),
  monthly_price numeric(12,2) check (monthly_price > 0),
  rental_mode public.rental_mode not null,
  status public.property_status not null default 'PENDING',
  rejection_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint rental_mode_has_price check (
    (rental_mode = 'SHORT_TERM' and short_term_price is not null) or
    (rental_mode = 'LONG_TERM' and monthly_price is not null) or
    (rental_mode = 'BOTH' and short_term_price is not null and monthly_price is not null)
  )
);

create table public.property_images (
  id uuid primary key default gen_random_uuid(),
  property_id uuid not null references public.properties(id) on delete cascade,
  storage_path text not null unique,
  alt_text text,
  is_cover boolean not null default false,
  sort_order smallint not null default 0,
  created_at timestamptz not null default now()
);
create unique index one_cover_per_property on public.property_images(property_id) where is_cover;

create table public.amenities (
  id bigint generated by default as identity primary key,
  name text not null unique,
  icon text,
  created_at timestamptz not null default now()
);

create table public.property_amenities (
  property_id uuid not null references public.properties(id) on delete cascade,
  amenity_id bigint not null references public.amenities(id) on delete restrict,
  primary key (property_id, amenity_id)
);

-- AVAILABLE is implicit when no BLOCKED/RESERVED/BOOKED range exists.
create table public.availability (
  id uuid primary key default gen_random_uuid(),
  property_id uuid not null references public.properties(id) on delete cascade,
  booking_id uuid,
  start_date date not null,
  end_date date not null,
  status public.availability_status not null,
  reason text,
  created_by uuid not null references public.profiles(id),
  created_at timestamptz not null default now(),
  constraint availability_dates_valid check (end_date > start_date),
  constraint availability_source_valid check (
    (status = 'BLOCKED' and booking_id is null) or
    (status in ('RESERVED', 'BOOKED') and booking_id is not null)
  )
);

create table public.bookings (
  id uuid primary key default gen_random_uuid(),
  property_id uuid not null references public.properties(id) on delete restrict,
  renter_id uuid not null references public.profiles(id) on delete restrict,
  owner_id uuid not null references public.profiles(id) on delete restrict,
  rental_mode public.rental_mode not null check (rental_mode <> 'BOTH'),
  start_date date not null,
  end_date date not null,
  occupants smallint not null check (occupants > 0),
  estimated_cost numeric(12,2) not null check (estimated_cost >= 0),
  status public.booking_status not null default 'PENDING',
  rejection_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint booking_dates_valid check (end_date > start_date),
  constraint renter_not_owner check (renter_id <> owner_id),
  constraint no_overlapping_live_bookings exclude using gist (
    property_id with =,
    daterange(start_date, end_date, '[)') with &&
  ) where (status in ('PENDING', 'APPROVED', 'ACTIVE'))
);

